import sys

## container = [] creates an empty list. One reference: the name container.
container = []
print(sys.getrefcount(container)) 

## container.append(container) puts the list inside itself. A list stores
##  references to its items, so the list now holds a reference to itself. 
##  That’s two real references: the name and its own slot. getrefcount would report 3.
container.append(container)
print(sys.getrefcount(container))

## we delete the last reference to the container, but not the container itsself causing a memory leak 
## the memory is automatically dereferenced when the count equals 0, but this wont always work.
del container
print("The reference count is now 0")

