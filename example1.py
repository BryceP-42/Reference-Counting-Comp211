import sys

## x = object() creates an object, and the name x is one reference to it.
x = object()

## sys.getrefcount(x) prints 2, not 1. Passing x into the function 
##  creates a temporary extra reference for the duration of the call,
##  so the real count is 1 and the function reports one more.
print(sys.getrefcount(x))   # 2

## y = x doesn’t copy anything. It makes a second name point at the same object, so the count goes up by one and the function reports 3.
y = x
print(sys.getrefcount(x))   # 3

## del y removes the name y, not the object. The count drops back down, and the function reports 2 again.
del y
print(sys.getrefcount(x))   # 2

